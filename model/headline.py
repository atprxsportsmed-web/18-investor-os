"""Prints the headline numbers that the deck and kit quote, read from the finished workbook."""
import openpyxl
v = openpyxl.load_workbook("output/18_Golf_Performance_Club_Financial_Model.xlsx", data_only=True)
S, I, U, SU = v["Summary"], v["Investor returns"], v["Unit economics"], v["Sources and uses"]
k = lambda x: f"${x/1000:,.0f}K"
r = lambda x: f"{x:.2f}x"
p = lambda x: f"{x*100:.0f}%"
print("# Current headline numbers (generated by model/headline.py, do not edit by hand)\n")
print("Source of truth for every number on the deck and kit. After any model change, run model/build.sh, then update the slides listed in CLAUDE.md.\n")
print("| Metric | Conservative | Base | Upside |\n|---|---|---|---|")
rows = [("Total capital required", 9, k), ("Surplus vs $500K raise", 11, k), ("Members at month 36", 15, lambda x: f"{x:.0f}"),
        ("First profitable month", 16, lambda x: str(x)), ("Year 3 revenue", 20, k), ("Year 3 operating profit", 23, k)]
for name, row, f in rows:
    print(f"| {name} | " + " | ".join(f(S.cell(row, c).value) if isinstance(S.cell(row, c).value, (int, float)) else str(S.cell(row, c).value) for c in (2, 3, 4)) + " |")
print(f"\n- Break-even: about {S['B27'].value:.1f} members; fixed costs {S['B25'].value:,.0f} per month before contingency")
print(f"- Contribution per member: ${U['B10'].value:,.2f} (dues ${U['B6'].value:,.0f} + add-on share ${U['B7'].value:,.0f} - card fees and follow-up ${-U['B9'].value:,.2f})")
print("\n## Base case investor returns (5 years)\n\n| Structure | Cash only | With exit | IRR with exit |\n|---|---|---|---|")
for lab, rc, re_, ri in (("A. Straight equity", 21, 18, 15), ("B. Priority payback to 1.0x", 22, 19, 16), ("C. Priority payback to 1.5x", 23, 20, 17)):
    print(f"| {lab} | {r(I.cell(rc,3).value)} | {r(I.cell(re_,3).value)} | {p(I.cell(ri,3).value) if isinstance(I.cell(ri,3).value,(int,float)) else 'n/a'} |")
print(f"\nWith exit, Conservative {r(min(I.cell(x,2).value for x in (18,19,20)))} to {r(max(I.cell(x,2).value for x in (18,19,20)))}; Upside {r(min(I.cell(x,4).value for x in (18,19,20)))} to {r(max(I.cell(x,4).value for x in (18,19,20)))}.")
print("\n## Funding stages\n")
for rr in range(29, 33): print(f"- {SU.cell(rr,1).value}: {k(SU.cell(rr,2).value)}")
